// Run: node tests/offers-page-ui.cjs (requires jsdom).
const { JSDOM } = require('jsdom');
const fs = require('fs');
const assert = require('node:assert/strict');
const { execFileSync } = require('child_process');
// Exercise the real PHP renderer and its offer fixtures rather than duplicating markup.
const html = execFileSync('php', ['-r', 'ob_start(); require "tests/offers-structured-test.php"; ob_end_clean(); echo $pinned_html;'], { encoding: 'utf8' });
const dom = new JSDOM(html, { url: 'https://hithean.test/uu-dai/?xem=san-pham', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
w.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
w.HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); this.dispatchEvent(new w.Event('close')); };
Object.defineProperty(w.document, 'readyState', { configurable: true, value: 'loading' });
w.eval(fs.readFileSync('pages/uu-dai/uu-dai.js', 'utf8'));
const d = w.document;
w.HTMLElement.prototype.scrollIntoView = function () {};
w.matchMedia = () => ({ matches: false });
// WordPress prints the footer bar after footer scripts; it is absent during script evaluation.
d.body.insertAdjacentHTML('beforeend', '<button data-ho-mode-toggle><span data-ho-mode-label>Theo SP</span></button>');
Object.defineProperty(d, 'readyState', { configurable: true, value: 'complete' });
d.dispatchEvent(new w.Event('DOMContentLoaded'));
const toggle = d.querySelector('[data-ho-mode-toggle]');
assert.equal(toggle.textContent, 'Theo CT', 'late footer button reflects URL-selected product view');
toggle.querySelector('span').click();
assert.equal(d.querySelector('[data-ho-page]').dataset.hoMode, 'programs', 'late footer button switches to programs');
assert.ok(!d.querySelector('[data-ho-panel="programs"]').hidden && d.querySelector('[data-ho-panel="products"]').hidden);
assert.equal(toggle.textContent, 'Theo SP');
toggle.click();
assert.equal(d.querySelector('[data-ho-page]').dataset.hoMode, 'products', 'late footer button switches back to products');
assert.ok(!d.querySelector('[data-ho-panel="products"]').hidden && d.querySelector('[data-ho-panel="programs"]').hidden);
assert.equal(new URL(w.location.href).searchParams.get('xem'), 'san-pham');
assert.equal(w.sessionStorage.getItem('ho-mode'), 'products');

const card = d.querySelector('[data-ho-product-card]:not([hidden])');
assert.ok(card, 'fixture has a visible product');
const dialog = card.querySelector('dialog');
const cta = card.querySelector('.ho-offer-preview');
assert.ok(!dialog.open, 'details initially closed');
assert.equal(card.querySelectorAll('.ho-card-body [data-ho-rule]').length, 0, 'full details stay out of grid body');
cta.click();
assert.ok(dialog.open && d.documentElement.classList.contains('ho-modal-open'), 'CTA opens modal and locks page');
dialog.querySelector('[data-ho-close]').click();
assert.ok(!dialog.open && !d.documentElement.classList.contains('ho-modal-open'), 'close unlocks page');
assert.equal(d.activeElement, cta, 'focus returns to CTA');
card.querySelector('h3 a').click();
assert.ok(dialog.open, 'product name opens popup');
dialog.close();
card.querySelector('.ho-product-price').click();
assert.ok(dialog.open, 'card body opens popup');
dialog.close();
const visual = card.querySelector('.ho-card-visual');
visual.click();
assert.ok(dialog.open, 'image opens popup');
dialog.close();
assert.equal(d.activeElement, visual, 'focus returns to actual image trigger');
const rules = [...card.querySelectorAll('[data-ho-rule]')];
assert.ok(rules.length > 1, 'fixture covers multiple offers');
rules[0].dataset.hoUntil = '1';
d.dispatchEvent(new w.Event('visibilitychange'));
assert.ok(rules[0].hidden, 'expired individual offer hides');
assert.equal(cta.querySelector('[data-ho-preview-count]').textContent, `Xem ${rules.length - 1} ưu đãi`, 'preview count refreshes');
assert.equal(cta.querySelector('[data-ho-preview-title]').textContent, rules[1].querySelector('.hithean-offer-card__title').textContent, 'preview uses next active offer');
cta.click();
rules.forEach(rule => { rule.dataset.hoUntil = '1'; });
d.dispatchEvent(new w.Event('visibilitychange'));
assert.ok(card.hidden && !dialog.open, 'last expiry removes card and closes popup');
assert.ok(!d.documentElement.classList.contains('ho-modal-open'), 'expiry releases scroll lock');
w.close();
console.log('PASS: product offer popup, focus, card triggers and expiry behavior');
